// Package courier is the Git / Release Manager (FR-90–FR-94, FR-44). It runs the
// workflow defined by the "git-workflow" standard (FR-91) using deterministic git and
// forge commands, and calls an agent only for judgment work (conflicts, release notes).
package courier

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"time"

	"github.com/techmuch/go-build-it/internal/access"
	"github.com/techmuch/go-build-it/internal/gitx"
	"github.com/techmuch/go-build-it/internal/history"
	"github.com/techmuch/go-build-it/internal/projects"
	"github.com/techmuch/go-build-it/internal/queue"
	"github.com/techmuch/go-build-it/internal/sessions"
	"github.com/techmuch/go-build-it/internal/standards"
)

// Name is the persona name Courier acts as.
const Name = "Courier"

// Workflow is the parsed git workflow for a project.
type Workflow struct {
	RequirePR     bool   `json:"requirePr"`
	Squash        bool   `json:"squash"`
	HumanApproval bool   `json:"humanApproval"`
	LensReview    bool   `json:"lensReview"`
	TagReleases   bool   `json:"tagReleases"`
	Pages         bool   `json:"pages"`
	Source        string `json:"source"` // which standard (and override) it came from
}

// ParseWorkflow reads workflow switches from the standard's Markdown (FR-91).
func ParseWorkflow(md string) Workflow {
	l := strings.ToLower(md)
	has := func(re string) bool { return regexp.MustCompile(re).MatchString(l) }
	return Workflow{
		RequirePR:     has(`\b(pr|mr|pull request|merge request)\b`) && !has(`no (pr|pull request)`),
		Squash:        has(`squash`),
		HumanApproval: has(`human approv|human approves|you approve`),
		LensReview:    has(`lens|reviewer`),
		TagReleases:   has(`yyyy\.mm\.dd\.n|calver|tag`),
		Pages:         has(`pages`),
	}
}

// Courier runs git operations.
type Courier struct {
	git       *gitx.Git
	forge     *gitx.ForgeCLI
	hist      *history.Recorder
	projects  *projects.Service
	queue     *queue.Service
	standards *standards.Service
	worktree  func(projectID, taskID string) string
	// Notes optionally asks an agent to write release notes from commit subjects (FR-93).
	Notes func(ctx context.Context, projectID, tag string, subjects []string) (string, error)
	// AfterPush is called once a task branch is pushed (or committed locally), to open the review.
	AfterPush func(ctx context.Context, t queue.Task) error
}

// New returns a Courier.
func New(g *gitx.Git, f *gitx.ForgeCLI, h *history.Recorder, p *projects.Service, q *queue.Service, st *standards.Service, worktree func(string, string) string) *Courier {
	return &Courier{git: g, forge: f, hist: h, projects: p, queue: q, standards: st, worktree: worktree}
}

func (c *Courier) ctx(ctx context.Context) context.Context { return access.Persona(ctx, Name) }

// Workflow returns the effective workflow for a project.
func (c *Courier) Workflow(ctx context.Context, projectID string) Workflow {
	stds, _ := c.standards.Effective(ctx, projectID)
	for _, s := range stds {
		if s.ID == "git-workflow" {
			w := ParseWorkflow(s.Body)
			w.Source = "standard git-workflow rev " + fmt.Sprint(s.Rev)
			return w
		}
	}
	return Workflow{RequirePR: true, Squash: true, HumanApproval: true, LensReview: true, TagReleases: true, Pages: true, Source: "built-in default (ADR-003)"}
}

// Completed commits a finished session's work, pushes it and opens the PR/MR (FR-92, FR-93).
func (c *Courier) Completed(ctx context.Context, s sessions.Session, t queue.Task) error {
	ctx = c.ctx(ctx)
	p, err := c.projects.Get(ctx, t.ProjectID)
	if err != nil {
		return err
	}
	dir := s.Workdir
	c.cleanGenerated(ctx, dir)
	msg := fmt.Sprintf("%s: %s\n\nBy %s (%s, session %s)", t.ID, t.Title, s.MemberID, s.Harness, s.ID)
	committed, err := c.git.CommitAll(ctx, dir, msg, s.MemberID)
	if err != nil {
		return fmt.Errorf("commit: %w", err)
	}
	if committed {
		c.hist.Must(ctx, history.Event{ProjectID: p.ID, Type: "git.commit", Subject: t.ID, Summary: fmt.Sprintf("Committed %s on %s", t.ID, t.Branch), Why: "session " + s.ID + " completed"})
	}
	if err := c.PushTask(ctx, p, t); err != nil {
		return err
	}
	if c.AfterPush != nil {
		t, _ = c.queue.Get(ctx, t.ID)
		return c.AfterPush(ctx, t)
	}
	return nil
}

// cleanGenerated keeps generated instruction files out of commits: untracked ones are
// removed, tracked ones (the project's own AGENTS.md etc.) are restored (FR-53).
func (c *Courier) cleanGenerated(ctx context.Context, dir string) {
	for _, f := range standards.InstructionFiles {
		p := filepath.Join(dir, f)
		b, err := os.ReadFile(p)
		if err != nil || !strings.Contains(string(b), "Generated by go-build-it") {
			continue
		}
		if _, err := c.git.Run(ctx, dir, "git", "ls-files", "--error-unmatch", f); err == nil {
			_, _ = c.git.Run(ctx, dir, "git", "checkout", "--", f)
		} else {
			_ = os.Remove(p)
		}
	}
}

// PushTask pushes a task branch and opens a PR when the workflow requires one.
func (c *Courier) PushTask(ctx context.Context, p projects.Project, t queue.Task) error {
	ctx = c.ctx(ctx)
	if p.Remote == "" {
		c.hist.Must(ctx, history.Event{ProjectID: p.ID, Type: "git.local", Subject: t.ID, Summary: "No remote: " + t.Branch + " kept locally", Why: "project has no origin"})
		return nil
	}
	if err := c.git.Push(ctx, c.worktree(p.ID, t.ID), t.Branch); err != nil {
		return fmt.Errorf("push %s: %w", t.Branch, err)
	}
	c.hist.Must(ctx, history.Event{ProjectID: p.ID, Type: "git.push", Subject: t.ID, Summary: "Pushed " + t.Branch, Why: "workflow step: push"})
	wf := c.Workflow(ctx, p.ID)
	if wf.RequirePR && t.PRURL == "" && (p.Forge == "github" || p.Forge == "gitlab") {
		base := c.git.DefaultBranch(ctx, p.Path)
		url, err := c.forge.CreatePR(ctx, p.Forge, c.worktree(p.ID, t.ID), t.Branch, base, t.ID+": "+t.Title, prBody(t))
		if err != nil {
			return fmt.Errorf("open PR: %w", err)
		}
		url = lastLine(url)
		if _, err := c.queue.Update(ctx, queue.Task{ID: t.ID, PRURL: url}); err != nil {
			return err
		}
		c.hist.Must(ctx, history.Event{ProjectID: p.ID, Type: "git.pr", Subject: t.ID, Summary: "Opened " + url, Why: "workflow requires a PR/MR (" + wf.Source + ")"})
	}
	return nil
}

func prBody(t queue.Task) string {
	b := fmt.Sprintf("Task %s · role %s\n\n%s\n", t.ID, t.Role, t.Description)
	if len(t.Reqs) > 0 {
		b += "\nRequirements: " + strings.Join(t.Reqs, ", ") + "\n"
	}
	return b + "\nOpened by Courier (go-build-it). Review happens in go-build-it."
}

func lastLine(s string) string {
	s = strings.TrimSpace(s)
	if i := strings.LastIndex(s, "\n"); i >= 0 {
		return strings.TrimSpace(s[i+1:])
	}
	return s
}

// Merge merges an approved task (squash per workflow), cleans up the worktree and marks it done.
func (c *Courier) Merge(ctx context.Context, taskID string) error {
	ctx = c.ctx(ctx)
	t, err := c.queue.Get(ctx, taskID)
	if err != nil {
		return err
	}
	p, err := c.projects.Get(ctx, t.ProjectID)
	if err != nil {
		return err
	}
	wf := c.Workflow(ctx, p.ID)
	switch {
	case t.PRURL != "":
		if err := c.forge.MergePR(ctx, p.Forge, p.Path, t.PRURL); err != nil {
			return fmt.Errorf("merge PR: %w", err)
		}
		_, _ = c.git.Run(ctx, p.Path, "git", "pull", "--ff-only")
	default:
		// Local merge into the default branch (no remote/PR).
		base := c.git.DefaultBranch(ctx, p.Path)
		if cur := c.git.CurrentBranch(ctx, p.Path); cur != base {
			return fmt.Errorf("the project checkout is on %q, not %q; switch it before merging", cur, base)
		}
		if conflicts, err := c.git.Merge(ctx, p.Path, t.Branch, wf.Squash); err != nil {
			_, _ = c.git.Run(ctx, p.Path, "git", "reset", "--merge") // works for squash merges too (no MERGE_HEAD)
			c.hist.Must(ctx, history.Event{ProjectID: p.ID, Type: "git.conflict", Subject: t.ID, Summary: "Merge conflict in " + strings.Join(conflicts, ", "), Why: "handed back to the developer persona to resolve (FR-93)"})
			// Judgment work: the developer resolves the conflict on its branch, then the task is reviewed again.
			t.ContextNote = strings.TrimSpace(t.ContextNote + fmt.Sprintf("\n\nCourier could not merge %s into %s: conflicts in %s. Merge %s into your branch, resolve the conflicts, run the tests, and finish.", t.Branch, base, strings.Join(conflicts, ", "), base))
			_, _ = c.queue.Update(ctx, t)
			_, _ = c.queue.SetStatus(ctx, t.ID, queue.Queued, "merge conflict: back to the developer")
			return fmt.Errorf("merge conflict in %v: the task was requeued for the developer to resolve", conflicts)
		}
		if wf.Squash {
			if _, err := c.git.CommitAll(ctx, p.Path, t.ID+": "+t.Title+" (squash)", Name); err != nil {
				return err
			}
		}
	}
	_ = c.git.RemoveWorktree(ctx, p.Path, c.worktree(p.ID, t.ID))
	c.hist.Must(ctx, history.Event{ProjectID: p.ID, Type: "git.merge", Subject: t.ID, Summary: fmt.Sprintf("Merged %s (%s)", t.ID, map[bool]string{true: "squash", false: "merge"}[wf.Squash]), Why: "review approved"})
	_, err = c.queue.SetStatus(ctx, t.ID, queue.Done, "merged by Courier")
	return err
}

// EnsurePushed pushes any task branches that are done or in review but not on the remote (FR-94).
func (c *Courier) EnsurePushed(ctx context.Context) (int, error) {
	ctx = c.ctx(ctx)
	ps, err := c.projects.List(ctx)
	if err != nil {
		return 0, err
	}
	n := 0
	for _, p := range ps {
		if p.Remote == "" {
			continue
		}
		ts, _ := c.queue.List(ctx, queue.Filter{ProjectID: p.ID, Status: queue.Review})
		for _, t := range ts {
			dir := c.worktree(p.ID, t.ID)
			if _, err := os.Stat(dir); err != nil || t.Branch == "" {
				continue
			}
			out, err := c.git.Run(ctx, dir, "git", "rev-list", "--count", t.Branch, "--not", "--remotes")
			if err == nil && strings.TrimSpace(out) != "0" {
				if err := c.PushTask(ctx, p, t); err == nil {
					n++
				}
			}
		}
	}
	return n, nil
}

// Release tags the next CalVer, creates the forge release with notes and publishes Pages (FR-05, FR-44, FR-92).
type Release struct {
	Tag        string   `json:"tag"`
	Notes      string   `json:"notes"`
	ReleaseURL string   `json:"releaseUrl"`
	WebsiteURL string   `json:"websiteUrl"`
	Steps      []string `json:"steps"`
}

// Release runs the release workflow for a project.
func (c *Courier) Release(ctx context.Context, projectID string, dryRun bool) (Release, error) {
	ctx = c.ctx(ctx)
	p, err := c.projects.Get(ctx, projectID)
	if err != nil {
		return Release{}, err
	}
	var r Release
	tags := c.git.Tags(ctx, p.Path)
	r.Tag = gitx.NextCalVer(time.Now(), tags)
	rng := "HEAD"
	if last := c.git.LatestRelease(ctx, p.Path); last != nil {
		rng = last.Tag + "..HEAD"
	}
	subjects := c.git.Log(ctx, p.Path, rng)
	r.Notes = ReleaseNotes(r.Tag, subjects)
	if c.Notes != nil && len(subjects) > 0 && !dryRun {
		if better, err := c.Notes(ctx, p.ID, r.Tag, subjects); err == nil && strings.TrimSpace(better) != "" {
			r.Notes = better // an agent wrote the notes (FR-93); the commit list is the fallback
			r.Steps = append(r.Steps, "release notes written by an agent")
		}
	}
	if dryRun {
		r.Steps = append(r.Steps, "would tag "+r.Tag, fmt.Sprintf("would include %d commits", len(subjects)))
		return r, nil
	}
	push := p.Remote != ""
	if err := c.git.Tag(ctx, p.Path, r.Tag, "Release "+r.Tag, push); err != nil {
		return r, fmt.Errorf("tag: %w", err)
	}
	r.Steps = append(r.Steps, "tagged "+r.Tag)
	if push && (p.Forge == "github" || p.Forge == "gitlab") {
		if out, err := c.forge.CreateRelease(ctx, p.Forge, p.Path, r.Tag, r.Notes); err == nil {
			r.ReleaseURL = lastLine(out)
			r.Steps = append(r.Steps, "created forge release")
		} else {
			r.Steps = append(r.Steps, "forge release failed: "+err.Error())
		}
		if c.Workflow(ctx, p.ID).Pages && p.Forge == "github" {
			if url, err := c.forge.EnsurePages(ctx, p.Slug(), p.Path); err == nil {
				r.WebsiteURL = url
				_, _ = c.projects.Update(ctx, p.ID, "", "", "", url, "")
				r.Steps = append(r.Steps, "website published at "+url)
			} else {
				r.Steps = append(r.Steps, "pages: "+err.Error())
			}
		}
	}
	c.hist.Must(ctx, history.Event{ProjectID: p.ID, Type: "release.created", Subject: r.Tag, Summary: "Released " + p.ID + " " + r.Tag, Why: fmt.Sprintf("%d commits since the last release", len(subjects)),
		Data: history.Data(r)})
	return r, nil
}

// ReleaseNotes groups commit subjects into notes. An agent may rewrite them (FR-93).
func ReleaseNotes(tag string, subjects []string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "## %s\n\n", tag)
	if len(subjects) == 0 {
		b.WriteString("No changes since the last release.\n")
	}
	for _, s := range subjects {
		fmt.Fprintf(&b, "- %s\n", s)
	}
	return b.String()
}

// CommitArtifact writes a file in a project repo and commits only that path (FR-45a, FR-46).
// It returns the new revision hash.
func (c *Courier) CommitArtifact(ctx context.Context, p projects.Project, rel, content, message, author string) (string, error) {
	ctx = c.ctx(ctx)
	clean := filepath.Clean(rel)
	if strings.HasPrefix(clean, "..") || filepath.IsAbs(clean) {
		return "", fmt.Errorf("invalid artifact path %q", rel)
	}
	full := filepath.Join(p.Path, clean)
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		return "", err
	}
	if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
		return "", err
	}
	if _, err := c.git.Run(ctx, p.Path, "git", "add", "--", clean); err != nil {
		return "", err
	}
	args := []string{"-c", "user.name=" + firstNonEmpty(author, Name), "-c", "user.email=courier@go-build-it.local", "commit", "-m", message, "--", clean}
	if _, err := c.git.Run(ctx, p.Path, "git", args...); err != nil {
		if strings.Contains(err.Error(), "nothing to commit") || strings.Contains(err.Error(), "no changes added") {
			return "", fmt.Errorf("no changes to save")
		}
		return "", err
	}
	hash, _ := c.git.Run(ctx, p.Path, "git", "rev-parse", "--short", "HEAD")
	if p.Remote != "" {
		if br := c.git.CurrentBranch(ctx, p.Path); br != "" {
			if err := c.git.Push(ctx, p.Path, br); err != nil {
				c.hist.Must(ctx, history.Event{ProjectID: p.ID, Type: "git.push_failed", Subject: clean, Summary: "Could not push artifact revision", Why: err.Error()})
			}
		}
	}
	c.hist.Must(ctx, history.Event{ProjectID: p.ID, Type: "artifact.revised", Subject: clean, Summary: fmt.Sprintf("Committed %s (%s)", clean, hash), Why: message,
		Data: history.Data(map[string]any{"hash": hash, "author": author})})
	return hash, nil
}

func firstNonEmpty(a ...string) string {
	for _, s := range a {
		if s != "" {
			return s
		}
	}
	return ""
}
