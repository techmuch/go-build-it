// Command gen writes internal/herdr/types.gen.go from herdr's published API schema
// (internal/herdr/schema/herdr-api.schema.json, from `herdr api schema --json`). NFR-32.
//
//	go run ./internal/herdr/gen            # rewrite types.gen.go
//	go run ./internal/herdr/gen -check     # exit 1 if types.gen.go is stale
//
// Only the types go-build-it uses are generated (see roots). A removed method,
// type or field that go-build-it relies on makes generation or the build fail.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
)

// Methods go-build-it calls. Generation fails if the schema no longer has one.
var methods = []string{
	"ping", "session.snapshot", "workspace.create", "workspace.list", "workspace.get", "workspace.close", "workspace.report_metadata",
	"worktree.open", "worktree.list", "tab.create", "agent.list", "agent.get", "agent.start", "agent.prompt", "agent.wait",
	"agent.send_keys", "agent.rename", "agent.focus", "agent.view.set", "pane.focus", "pane.get", "pane.list", "pane.read", "pane.close", "pane.send_text",
	"pane.report_agent", "pane.report_agent_session", "pane.release_agent", "pane.report_metadata", "notification.show",
	"events.subscribe", "integration.list", "integration.install",
}

var roots = map[string][]string{
	"request": {"WorkspaceCreateParams", "WorktreeOpenParams", "AgentStartParams", "AgentPromptParams", "AgentWaitParams", "AgentTarget",
		"AgentSendKeysParams", "AgentRenameParams", "PaneReportMetadataParams", "WorkspaceReportMetadataParams", "NotificationShowParams",
		"PaneReportAgentParams", "PaneReleaseAgentParams", "PaneReadParams", "IntegrationInstallParams"},
	"success_response": {"AgentInfo", "PaneInfo", "WorkspaceInfo", "TabInfo", "WorktreeInfo", "IntegrationInfo", "SessionSnapshot",
		"PaneReadResult", "ServerCapabilities"},
}

type schema map[string]any

func main() {
	check := flag.Bool("check", false, "fail if types.gen.go is out of date")
	flag.Parse()
	_, self, _, _ := runtime.Caller(0)
	dir := filepath.Dir(filepath.Dir(self))
	out, err := Generate(filepath.Join(dir, "schema", "herdr-api.schema.json"))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	target := filepath.Join(dir, "types.gen.go")
	if *check {
		cur, _ := os.ReadFile(target)
		if !bytes.Equal(cur, out) {
			fmt.Fprintln(os.Stderr, "internal/herdr/types.gen.go is stale: run go run ./internal/herdr/gen")
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(target, out, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

type gen struct {
	root    schema
	section string
	defs    schema
	done    map[string]bool
	queue   []string
	b       *bytes.Buffer
	prefix  string
}

// Generate renders the Go source for the schema at path.
func Generate(path string) ([]byte, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var root schema
	if err := json.Unmarshal(raw, &root); err != nil {
		return nil, err
	}
	b := &bytes.Buffer{}
	fmt.Fprintf(b, "// Code generated by go run ./internal/herdr/gen; DO NOT EDIT.\n// Source: herdr api schema (protocol %v, schema_version %v).\n\npackage herdr\n\n", root["protocol"], root["schema_version"])
	fmt.Fprintf(b, "// SchemaProtocol is the herdr protocol number of the vendored schema.\nconst SchemaProtocol = %v\n\n", root["protocol"])
	schemas := root["schemas"].(map[string]any)
	req := schemas["request"].(map[string]any)
	have := map[string]bool{}
	for _, alt := range req["oneOf"].([]any) {
		m := alt.(map[string]any)["properties"].(map[string]any)["method"].(map[string]any)["const"].(string)
		have[m] = true
	}
	b.WriteString("// Methods go-build-it relies on; each exists in the vendored schema.\nconst (\n")
	sort.Strings(methods)
	for _, m := range methods {
		if !have[m] {
			return nil, fmt.Errorf("herdr schema no longer has method %q", m)
		}
		fmt.Fprintf(b, "\tMethod%s = %q\n", goName(strings.NewReplacer(".", "_").Replace(m)), m)
	}
	b.WriteString(")\n\n// RequiredMethods lists every method above, for the runtime compatibility check.\nvar RequiredMethods = []string{")
	for _, m := range methods {
		fmt.Fprintf(b, "%q, ", m)
	}
	b.WriteString("}\n\n")
	emitted := map[string]bool{}
	for _, sec := range []string{"request", "success_response"} {
		s := schemas[sec].(map[string]any)
		g := &gen{root: root, section: sec, defs: s["$defs"].(map[string]any), done: emitted, b: b}
		for _, r := range roots[sec] {
			if _, ok := g.defs[r]; !ok {
				return nil, fmt.Errorf("herdr schema %s no longer has %s", sec, r)
			}
			g.want(r)
		}
		for len(g.queue) > 0 {
			n := g.queue[0]
			g.queue = g.queue[1:]
			g.emit(n)
		}
	}
	src := b.Bytes()
	if bytes.Contains(src, []byte("json.RawMessage")) {
		src = bytes.Replace(src, []byte("package herdr\n"), []byte("package herdr\n\nimport \"encoding/json\"\n"), 1)
	}
	return format.Source(src)
}

func (g *gen) want(name string) string {
	if !g.done[name] {
		g.done[name] = true
		g.queue = append(g.queue, name)
	}
	return name
}

func (g *gen) emit(name string) {
	d := g.defs[name].(map[string]any)
	if desc, ok := d["description"].(string); ok {
		fmt.Fprintf(g.b, "// %s: %s\n", name, oneLine(desc))
	} else {
		fmt.Fprintf(g.b, "// %s mirrors herdr's %s schema.\n", name, name)
	}
	if enum, ok := d["enum"].([]any); ok {
		fmt.Fprintf(g.b, "type %s string\n\nconst (\n", name)
		for _, e := range enum {
			fmt.Fprintf(g.b, "\t%s%s %s = %q\n", name, goName(fmt.Sprint(e)), name, e)
		}
		g.b.WriteString(")\n\n")
		return
	}
	props, ok := d["properties"].(map[string]any)
	if !ok {
		fmt.Fprintf(g.b, "type %s = %s\n\n", name, g.typ(d, true))
		return
	}
	req := map[string]bool{}
	if rs, ok := d["required"].([]any); ok {
		for _, r := range rs {
			req[r.(string)] = true
		}
	}
	keys := make([]string, 0, len(props))
	for k := range props {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	fmt.Fprintf(g.b, "type %s struct {\n", name)
	for _, k := range keys {
		p := props[k].(map[string]any)
		tag := k
		if !req[k] {
			tag += ",omitempty"
		}
		fmt.Fprintf(g.b, "\t%s %s `json:%q`\n", goName(k), g.typ(p, req[k]), tag)
	}
	g.b.WriteString("}\n\n")
}

func (g *gen) typ(p map[string]any, required bool) string {
	if ref, ok := p["$ref"].(string); ok {
		return g.refType(ref)
	}
	for _, key := range []string{"anyOf", "oneOf"} {
		if alts, ok := p[key].([]any); ok {
			var nonNull []map[string]any
			for _, a := range alts {
				am := a.(map[string]any)
				if am["type"] == "null" {
					continue
				}
				nonNull = append(nonNull, am)
			}
			if len(nonNull) == 1 && len(alts) == 2 {
				t := g.typ(nonNull[0], true)
				if isStruct(t, g) {
					return "*" + t
				}
				return t
			}
			return "json.RawMessage"
		}
	}
	if _, ok := p["const"]; ok {
		return "string"
	}
	t := p["type"]
	nullable := false
	if ts, ok := t.([]any); ok {
		for _, x := range ts {
			if x == "null" {
				nullable = true
			} else {
				t = x
			}
		}
	}
	var base string
	switch t {
	case "string":
		base = "string"
	case "integer":
		base = "int64"
	case "number":
		base = "float64"
	case "boolean":
		base = "bool"
	case "array":
		items, _ := p["items"].(map[string]any)
		if items == nil {
			return "[]json.RawMessage"
		}
		return "[]" + g.typ(items, true)
	case "object":
		if ap, ok := p["additionalProperties"].(map[string]any); ok {
			return "map[string]" + g.typ(ap, true)
		}
		return "json.RawMessage"
	default:
		return "json.RawMessage"
	}
	if nullable {
		return "*" + base
	}
	return base
}

func isStruct(t string, g *gen) bool {
	if d, ok := g.defs[t].(map[string]any); ok {
		_, has := d["properties"]
		return has
	}
	return false
}

func (g *gen) refType(ref string) string {
	parts := strings.Split(ref, "/")
	return g.want(parts[len(parts)-1])
}

var acronyms = map[string]string{"id": "ID", "ids": "IDs", "url": "URL", "cwd": "Cwd", "api": "API", "ms": "Ms", "px": "Px", "seq": "Seq", "ok": "OK", "argv": "Argv"}

func goName(s string) string {
	var out strings.Builder
	for _, part := range strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' || r == '.' || r == ' ' || r == ':' }) {
		if a, ok := acronyms[strings.ToLower(part)]; ok {
			out.WriteString(a)
			continue
		}
		out.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	if out.Len() == 0 {
		return "X"
	}
	r := out.String()
	if r[0] >= '0' && r[0] <= '9' {
		r = "N" + r
	}
	return r
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }
